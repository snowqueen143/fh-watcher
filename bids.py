def detect_kind(text: str) -> str:
    low = text.lower()
    for kind, pattern in KINDS:
        if re.search(pattern, low):
            return kind
    return "python"


def suggest_price(kind: str, budget: dict | None) -> str:
    if budget and budget.get("amount"):
        amount, cur = budget["amount"], budget.get("currency", "UAH")
        step = 10 if cur in ("USD", "EUR") else 500
        price = max(step, round(amount * 0.8 / step) * step)
        return f"{price} {cur}"
    return f"{DEFAULT_PRICE[kind]} UAH"


def make_bid(name: str, description: str, budget: dict | None) -> tuple[str, str]:
    """Возвращает (тип задачи, текст отклика)."""
    text = f"{name}\n{description}"
    lang = "ua" if UA_LETTERS.search(text) else "ru"
    kind = detect_kind(text)
    t = TEXT[lang]
    days = (DEFAULT_DAYS if lang == "ua" else DEFAULT_DAYS_RU)[kind]
    short_name = name.strip().rstrip(".")
    if len(short_name) > 70:
        short_name = short_name[:67].rstrip() + "..."
    lines = [
        t["hello"].format(name=short_name),
        "",
        t["how"],
        *[f"• {b}" for b in t[kind]],
        "",
        t["terms"].format(days=days, price=suggest_price(kind, budget)),
        t["bye"],
        "",
        t["q"][kind],
    ]
    return kind, "\n".join(lines)
